<details class="reveal"><summary>參考答案：帳本與結算</summary>
<ul>
<li>帳本是<b>只能新增（append-only）的複式帳本（double-entry ledger）</b>。每一筆資金移動都是一對加起來等於零的資料列。餘額就是把這些列加總起來，另外有一個快取的總額，在同一筆交易（transaction）裡更新。</li>
<li>每個操作都帶一個<b>冪等鍵（idempotency key）</b>，並且加上唯一約束（unique constraint）：下注 ID、對局 ID、區塊鏈交易雜湊。重複的請求會查到這個鍵，然後什麼都不做。</li>
<li>下注時，用一次原子性的條件式更新把資金<b>預先保留</b>起來。結算時，在同一筆交易裡釋放這筆預先保留（reservation）並寫入結果。</li>
<li>對局結束時，房間伺服器把結果和一筆<b>寄件匣（outbox）</b>資料列一起寫入。背景工作者讀寄件匣，再去呼叫帳本。就算工作者當掉後重複呼叫，有冪等鍵擋著也不會出事。</li>
<li><b>存款：</b>監看程式等到確認數夠了，再透過帳本入帳，用交易雜湊當鍵。</li>
<li><b>提款：</b>先做風險檢查，再向簽章服務（signer）送出請求，簽章服務會強制執行單筆和每日的限額。熱錢包（hot wallet）裡大約只放一天的提款量。</li>
<li>帳本選擇<b>一致性（consistency）優先於可用性（availability）</b>。主庫如果沒辦法跟備援確認一筆寫入，就拒絕那筆寫入。第三個可用區放一個小小的仲裁者，決定兩邊誰可以當主庫，這樣就不會兩邊同時當。</li>
<li>有一個背景工作持續檢查<b>所有分錄加起來等於零</b>，並且拿鏈上餘額和帳面對帳（reconciliation）。只要有任何差異，就會立刻呼叫值班人員。</li>
<li>歷史紀錄<b>按月分割</b>。按使用者分片先留著當後手，等到一台主庫再也吃不下寫入量時才用。</li>
</ul>
</details>
