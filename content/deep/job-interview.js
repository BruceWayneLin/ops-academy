<p>每個故事都寫成英文的 STAR 筆記，大聲講到不用看稿。轉職的人有一個優勢：你的開發經驗裡就有很多「跨到維運」的故事，例如主動接下部署、修好監控。把它們放進第 4 號和第 7 號，正好證明你轉換的動機是真的。</p>

