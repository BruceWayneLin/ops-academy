<h3>十、跟你的工作連起來</h3>
<ul>
<li><b>前端工程師</b>：你的故事庫裡很可能有「一次上線出事、怎麼回復」「一次說服團隊導入自動化測試」。這些都能直接套進第 1 號和第 4 號故事。系統設計時，你對瀏覽器和 CDN 的熟悉，是很多後端出身的人沒有的優勢。</li>
<li><b>遊戲工程師</b>：遊戲上線日的尖峰、伺服器在活動期間的負載、客戶端版本與伺服器版本的相容，這些經驗讓你在系統設計題裡講得出真實的取捨。用遊戲的例子講，面試官通常會很有興趣。</li>
