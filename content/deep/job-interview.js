<h4>演練：設計「猜高低」遊戲的全球排行榜</h4>
<p><b>釐清需求。</b>先問，不要猜：「排行榜是全球一個，還是每週重置？要即時嗎？大概多少玩家？」假設面試官回答：每天 100 萬個活躍玩家，每人平均玩 20 局，每局結束要更新分數；排行榜顯示前 100 名和自己的名次，延遲幾秒可以接受。</p>
<p><b>估算。</b>把數字算出來，而且邊算邊講：</p>
<ul>
<li>寫入：100 萬 × 20 = 每天 2,000 萬次。一天 86,400 秒，平均每秒約 230 次。尖峰抓平均的 5 倍，約每秒 1,200 次。</li>
