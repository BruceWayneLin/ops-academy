#!/usr/bin/env node
// Builds claude-page.html, the entry page for the private claude.ai version of the course.
// It differs from index.html in three ways: the styles are inlined, there is no <html>/<head>/<body>
// wrapper (claude.ai adds its own), and the owner's personal notes are always loaded.
// Usage: node tools/make-claude-page.js     -> writes claude-page.html, refreshes the course list in index.html,
//                                              and prints the files to publish with the claude.ai page
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'assets/style.css'), 'utf8');
const mods = fs.readdirSync(path.join(root, 'content')).filter(f => /^[a-z]+\d.*\.js$/.test(f)).sort();
const deepDir = path.join(root, 'content/deep');
const deeps = fs.existsSync(deepDir) ? fs.readdirSync(deepDir).filter(f => f.endsWith('.js')).sort().map(f => 'content/deep/' + f) : [];
const scripts = mods.map(f => 'content/' + f).concat(mods.map(f => 'content/zh/' + f), deeps, ['content/private.local.js'], fs.existsSync(path.join(root, 'content/library.local.js')) ? ['content/library.local.js'] : [], ['assets/app.js']);
// Other study material (EXTRA_LINKS) is no longer used: the owner's own courses live in content/library.local.js.
const extras = [];

const html = `<title>Skills Hub</title>
<meta name="claude:viewport-fit-sides" content="cover">
<style>
${css}
</style>
<script>
window.COURSE = [];
window.COURSE_ZH = [];
window.PRIVATE_NOTES = {};
function M(m) { COURSE.push(m); }
function MZ(m) { COURSE_ZH.push(m); }
function PRIVATE(o) { window.PRIVATE_NOTES = o || {}; }
window.DEEPS = {};
function DEEP(o) { Object.assign(window.DEEPS, o); }
window.EXTRA_LINKS = ${JSON.stringify(extras)};
</script>
<header class="top">
  <button id="menu" class="icon" aria-label="Menu">&#9776;</button>
  <a class="brand" href="#home">Skills<b>Hub</b></a>
  <div class="prog" title="Lessons completed">
    <div class="prog-track"><div id="prog-bar"></div></div>
    <span id="prog-n">0 / 0</span>
  </div>
  <div class="search">
    <input id="q" type="search" placeholder="Search lessons" autocomplete="off">
    <div id="hits" hidden></div>
  </div>
  <button id="lang" class="icon" aria-label="Switch language">中文</button>
</header>
<div class="shell">
  <nav id="side"></nav>
  <main id="main"></main>
</div>
${scripts.map(s => '<script src="' + s + '"></script>').join('\n')}
`;
fs.writeFileSync(path.join(root, 'claude-page.html'), html);
// The public entry page lists the same course files (English, then Chinese), between two markers.
const idxPath = path.join(root, 'index.html');
const idx = fs.readFileSync(idxPath, 'utf8');
const A = '<!-- course files: generated by tools/make-claude-page.js -->', Z = '<!-- /course files -->';
const tags = mods.map(f => 'content/' + f).concat(mods.map(f => 'content/zh/' + f), deeps).map(s => '<script src="' + s + '"></script>').join('\n');
fs.writeFileSync(idxPath, idx.slice(0, idx.indexOf(A) + A.length) + '\n' + tags + '\n' + idx.slice(idx.indexOf(Z)));
const files = scripts.concat(fs.existsSync(path.join(root, 'guide/index.html')) ? ['guide/index.html'] : []);
console.log(JSON.stringify(files.map(p => ({ path: p }))));
